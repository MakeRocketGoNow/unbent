/**
 * The mark for a provider, or null when there is none.
 *
 * `aria-hidden` throughout: the button's own text already names the provider, so a title
 * here would have a screen reader say "Google" twice.
 */
export function ProviderIcon({ provider }: { provider: string }) {
  if (provider === 'google') {
    return (
      <svg className="provider-icon" viewBox="0 0 24 24" aria-hidden="true" focusable="false">
        {GOOGLE.map((path) => (
          <path key={path.fill} d={path.d} fill={path.fill} />
        ))}
      </svg>
    );
  }

  const path = MONO[provider];
  if (!path) return null;

  return (
    <svg
      className="provider-icon"
      viewBox="0 0 24 24"
      aria-hidden="true"
      focusable="false"
      fill="currentColor"
    >
      <path d={path} />
    </svg>
  );
}
